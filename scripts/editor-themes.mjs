/**
 * Regenerates `src/shared/lib/code/editor/themes.generated.ts` from the
 * INSTALLED `@shikijs/themes`.
 *
 * The editor theme picker needs a colour for every theme BEFORE the theme's
 * module is loaded — a 65-card grid cannot fetch 1.3 MB of TextMate JSON to
 * draw its own swatches. So the chrome colours and three syntax accents are
 * read out of each theme at generation time and shipped as data.
 *
 * Two rules make the data honest:
 *
 * - **Every value is the theme's OWN.** `editor.background` and
 *   `editor.foreground` are the editor surface; the accents come from the
 *   theme's `tokenColors` for `keyword`, `string` and `comment` (first match
 *   wins, which is what TextMate resolution does for the plain scope names).
 * - **A key the theme omits falls back to a MIX of its own ink and background**,
 *   never to a colour from another theme. Several themes ship no
 *   `editor.selectionBackground` or no `editor.findMatchBackground`; borrowing
 *   one would make the swatch a lie about what selecting the theme does.
 *
 *   bun run scripts/editor-themes.mjs [--check]
 *
 * `--check` regenerates in memory and exits non-zero when the file on disk
 * differs, so a `@shikijs/themes` bump cannot leave the picker showing colours
 * the installed package no longer ships.
 */

import { readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');
const OUT = join(REPO, 'src/shared/lib/code/editor/themes.generated.ts');
const THEMES_DIR = join(REPO, 'node_modules/@shikijs/themes/dist');

/** `index` is the package's own barrel, not a theme. */
const ids = readdirSync(THEMES_DIR)
  .filter((file) => file.endsWith('.mjs') && file !== 'index.mjs')
  .map((file) => file.slice(0, -'.mjs'.length))
  .sort();

/** A colour mixed from the theme's own ink and background, for a key it omits. */
const mix = (colour, percent, base) => `color-mix(in srgb, ${colour} ${percent}%, ${base})`;

/** The first `tokenColors` entry naming one of `scopes` with a foreground. */
function accent(tokenColors, scopes) {
  for (const entry of tokenColors ?? []) {
    const scope = entry.scope;
    const list = Array.isArray(scope) ? scope : typeof scope === 'string' ? scope.split(',') : [];
    if (list.some((name) => scopes.includes(name.trim())) && entry.settings?.foreground) {
      return entry.settings.foreground;
    }
  }
  return null;
}

/** A single-quoted TS string literal, escaping what the label may contain. */
const quote = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const rows = [];
const loaders = [];

for (const id of ids) {
  const theme = (await import(`@shikijs/themes/${id}`)).default;
  const colors = theme.colors ?? {};
  const variant = theme.type === 'light' ? 'light' : 'dark';
  const bg = colors['editor.background'];
  const fg =
    colors['editor.foreground'] ??
    colors['foreground'] ??
    colors['terminal.foreground'] ??
    (variant === 'dark' ? '#e6e6e6' : '#1f2328');

  const tokenColors = theme.tokenColors ?? [];
  const addedGutter = colors['editorGutter.addedBackground'] ?? '#2ea043';
  const removedGutter = colors['editorGutter.deletedBackground'] ?? '#f85149';

  const fields = [
    quote(id),
    quote(theme.displayName ?? id),
    quote(variant),
    quote(bg),
    quote(fg),
    quote(colors['editorLineNumber.foreground'] ?? mix(fg, 38, bg)),
    quote(colors['editor.selectionBackground'] ?? mix(fg, 22, bg)),
    quote(colors['editorCursor.foreground'] ?? fg),
    quote(colors['editor.findMatchBackground'] ?? mix(fg, 18, bg)),
    quote(colors['editor.findMatchHighlightBackground'] ?? colors['editor.findMatchBackground'] ?? mix(fg, 30, bg)),
    quote(colors['panel.border'] ?? mix(fg, 16, bg)),
    quote(
      colors['diffEditor.insertedLineBackground'] ??
        colors['diffEditor.insertedTextBackground'] ??
        mix(addedGutter, 22, bg),
    ),
    quote(
      colors['diffEditor.removedLineBackground'] ??
        colors['diffEditor.removedTextBackground'] ??
        mix(removedGutter, 22, bg),
    ),
    quote(addedGutter),
    quote(removedGutter),
    quote(accent(tokenColors, ['keyword', 'storage', 'storage.type']) ?? fg),
    quote(accent(tokenColors, ['string', 'string.quoted', 'string.quoted.double']) ?? fg),
    quote(accent(tokenColors, ['comment', 'comment.line']) ?? fg),
  ];
  rows.push(`  [${fields.join(', ')}],`);
  loaders.push(`  ${quote(id)}: () => import('@shikijs/themes/${id}'),`);
}

const file = `/**
 * @license
 * SPDX-License-Identifier: MIT
 */

/**
 * GENERATED by \`scripts/editor-themes.mjs\` — do not edit by hand.
 *
 * One row per theme shipped by \`@shikijs/themes\`, in id order. Each row carries
 * the colours the editor CHROME needs (surface, gutter, selection, cursor, find,
 * border, the diff bands) plus three syntax accents for the picker's swatch, so
 * the settings grid can draw ${rows.length} cards without fetching a theme module.
 *
 * The field order is the tuple's type (\`EditorThemeRow\` in \`./themes.ts\`).
 * \`themes.test.ts\` re-derives every value from the installed package and fails on
 * drift, so a \`@shikijs/themes\` bump surfaces as a test failure rather than a
 * picker showing colours the package no longer ships.
 */

/** \`[id, label, variant, bg, fg, gutterFg, selection, cursor, find, findCurrent, border, added, removed, addedGutter, removedGutter, keyword, string, comment]\` */
export const EDITOR_THEME_ROWS = [
${rows.join('\n')}
] as const;

/** Lazy module loaders, so a theme nobody selects is never downloaded. */
export const EDITOR_THEME_LOADERS: Record<string, () => Promise<unknown>> = {
${loaders.join('\n')}
};
`;

const check = process.argv.includes('--check');
const current = await Bun.file(OUT).text().catch(() => '');

if (check) {
  if (current !== file) {
    console.error(`stale: ${OUT} does not match the installed @shikijs/themes — run \`bun run editor:themes\``);
    process.exit(1);
  }
  console.log(`up to date: ${rows.length} editor themes`);
} else {
  await Bun.write(OUT, file);
  console.log(`wrote ${rows.length} editor themes to ${OUT}`);
}
