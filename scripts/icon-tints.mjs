/**
 * Regenerate the per-icon hue table from the icons this repo actually imports.
 *
 * `color` mode gives every functional glyph its own hue, and the only stable
 * input is the icon's NAME — there is no artwork to colour. This script is what
 * turns that into data: it scans `src/` for `lucide-preact` imports, assigns a
 * hue by a stable hash, and writes `src/shared/lib/icons/tint-hues.generated.ts`.
 *
 * Why generated rather than hashed at render time: the tint is applied by CSS
 * (`[data-icon-style="color"] svg.lucide-<name> { --icon-hue: … }`), and CSS
 * cannot hash a class name. Why scanned rather than hand-listed: a table that
 * drifts from the imports is a table where a newly added icon silently keeps the
 * default hue, which looks like the mode is half-applied.
 *
 *   bun run icons:tints           # rewrite the table
 *   bun run icons:tints --check   # exit 1 when the table is stale (CI / tests)
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SRC = join(ROOT, 'src');
const TARGET = join(SRC, 'shared/lib/icons/tint-hues.generated.ts');

/** The wheel the hashes land on: 36 hues, 10° apart. */
const HUE_STEPS = 36;

/** FNV-1a — stable across runs and platforms, which a hash for stored data must be. */
function hash(value) {
  let h = 2166136261 >>> 0;
  for (const char of value) {
    h ^= char.codePointAt(0);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return h;
}

/** `src/**` files that can carry an icon import. */
async function sourceFiles(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
      out.push(...(await sourceFiles(path)));
    } else if (/\.(ts|tsx)$/.test(entry.name) && !entry.name.endsWith('.test.ts') && !entry.name.endsWith('.test.tsx')) {
      out.push(path);
    }
  }
  return out;
}

/** Every icon name imported from `lucide-preact`, deduplicated. */
async function importedIcons() {
  const names = new Set();
  for (const file of await sourceFiles(SRC)) {
    const source = await readFile(file, 'utf8');
    if (!source.includes("'lucide-preact'")) continue;
    for (const match of source.matchAll(/import\s+(?:type\s+)?\{([^}]*)\}\s+from\s+'lucide-preact'/g)) {
      for (const raw of match[1].split(',')) {
        const name = raw.trim().replace(/^type\s+/, '').split(/\s+as\s+/)[0].trim();
        // `LucideIcon` is the type of an icon, not one.
        if (!name || name === 'LucideIcon') continue;
        names.add(name);
      }
    }
  }
  return [...names].sort();
}

/** The signal icons keep a palette token instead of a generated hue. */
async function signalIcons() {
  const source = await readFile(join(SRC, 'shared/lib/icons/tint.ts'), 'utf8');
  const block = /export const ICON_TINTS:[\s\S]*?= \{([\s\S]*?)\n\};/.exec(source);
  if (!block) throw new Error('ICON_TINTS not found in tint.ts');
  return new Set([...block[1].matchAll(/^\s{2}([A-Za-z0-9]+):/gm)].map((m) => m[1]));
}

function render(rows) {
  const lines = rows.map(([name, hue]) => `  ${name}: ${hue},`);
  return `/**
 * @license
 * SPDX-License-Identifier: MIT
 */

/**
 * GENERATED by \`scripts/icon-tints.mjs\` — do not hand-edit.
 *
 * One hue per functional glyph, 36 hues 10° apart, assigned by a stable hash of
 * the icon name. The signal icons in \`tint.ts\` are deliberately absent: they
 * paint a palette token, because a trash can has to be the theme's error colour
 * and not whatever the hash said.
 *
 * Regenerate with \`bun run icons:tints\` after adding an icon. The suite fails
 * when this table and the imports disagree (\`icons:tints:check\`), so a stale
 * table cannot ship.
 */

export const ICON_HUES: Readonly<Record<string, number>> = {
${lines.join('\n')}
};
`;
}

const [icons, signals] = await Promise.all([importedIcons(), signalIcons()]);
const rows = icons
  .filter((name) => !signals.has(name))
  .map((name) => [name, (hash(name) % HUE_STEPS) * (360 / HUE_STEPS)]);

const next = render(rows);
const check = process.argv.includes('--check');
const current = await readFile(TARGET, 'utf8').catch(() => '');

if (check) {
  if (current !== next) {
    console.error('[icons:tints] stale — run `bun run icons:tints`');
    process.exit(1);
  }
  console.log(`[icons:tints] up to date (${rows.length} icons)`);
} else {
  await writeFile(TARGET, next);
  console.log(`[icons:tints] wrote ${rows.length} icons to ${relative(ROOT, TARGET)}`);
}