/** The model-dropdown persists its selection here (actionType 'selectModel');
 *  a spawn that arrives without an explicit provider/modelId falls back to it. */
const SELECTED_MODEL_KEY = 'omp_selected_model';

/** A JSON object, or `{}` for anything else. The mode flags are read off the
 *  result, and a non-object body must read as "no modes" rather than throw. */
function asRecord(value: unknown): Record<string, unknown> {
  return value && typeof value === 'object' && !Array.isArray(value) ? (value as Record<string, unknown>) : {};
}

async function loadPersistedModel(): Promise<{ provider: string; modelId: string } | null> {
  try {
    const db = await getDb();
    const row = await db.get('SELECT value FROM app_settings WHERE key = ?', [SELECTED_MODEL_KEY]);
    if (!row?.value) return null;
    const parsed = JSON.parse(row.value) as { provider?: unknown; modelId?: unknown; id?: unknown };
    const provider = typeof parsed.provider === 'string' ? parsed.provider : undefined;
    const modelId = typeof parsed.modelId === 'string' ? parsed.modelId : (typeof parsed.id === 'string' ? parsed.id : undefined);
    return provider && modelId ? { provider, modelId } : null;
  } catch {
    return null;
  }
}

// POST /api/agent/new — spawn a brand-new omp session and send the first
// prompt. Mirrors omp-web's /api/agent/new: the session id is generated by
// omp itself, so Kabmo adopts it via the URL param after the response.
export async function action({ request }: ActionFunctionArgs) {
  try {
    // MOCK mode has no agent process to start, and saying so with a CODE is what
    // lets the composer take its simulated path instead of reporting "Prompt not
    // sent: omp binary not found" — measured in the demo shell on a host without
    // omp, where the landing composer silently did nothing. Real spawn failures
    // still report, because they carry no `mock_mode`.
    if (isMockMode()) {
      return json({ error: 'Mock mode runs no agent process', code: 'mock_mode' }, { status: 400 });
    }
    const body = await request.json().catch(() => null);
    if (!body || typeof body.type !== 'string' || !body.type.trim()) {
      return json({ error: 'command type is required', code: 'command_type_required' }, { status: 400 });
    }
    const cwd = typeof body.cwd === 'string' && body.cwd.trim() ? body.cwd.trim() : undefined;
    if (!cwd) {
      return json({ error: 'cwd is required', code: 'cwd_required' }, { status: 400 });
    }

    // Trust a client-supplied mode only when valid; else use the persisted pick.
    const accessMode = isApprovalMode(body.accessMode) ? body.accessMode : await loadPersistedAccessMode();
    // The composer's Plan/Goal selection rides the spawn ENVIRONMENT, because a
    // brand-new session has no JSONL for `loadPersistedModes` to read: the
    // toggle was pressed on a pending `new-…` chat, whose server call cannot
    // reach a child that does not exist yet. Without this the button read
    // "Leave plan mode" over a session that was born with plan mode off, and
    // flipped back the moment the spawn was adopted (measured).
    //
    // A selection that differs from the prewarmed entry's own kills that entry
    // and cold-spawns (`startNewRpcSession`), which is why the prewarm carries
    // no modes: the first real selection always wins over it.
    // `parseModeSelection` reads the FLAGS off the body it is given (that is
    // what `POST /api/agent/:id` sends), while this route nests them under
    // `modes`. Passing the body straight through therefore parsed `{}` and
    // spawned with an EMPTY selection — the client's pick was silently dropped
    // (measured: `modes:{plan:true}` produced a child reporting `plan: null`).
    const modes = body.modes !== undefined ? parseModeSelection(asRecord(body.modes)) : null;
    const modeEnv = modes ? kabmoModeEnv(modes) : undefined;
    // A harness other than omp's RPC runs over ACP. The pick is validated
    // against the catalog, so a typo cannot spawn an arbitrary binary.
    const harness = harnessDescriptor(typeof body.harness === 'string' ? body.harness : null) ? body.harness as HarnessId : 'omp-rpc';
    // startNewRpcSession adopts the prewarmed idle process for this cwd when
    // one exists (fired by the sidebar's New Session click) and otherwise
    // cold-spawns — same contract, minus the boot wait when prewarmed.
    if (harness !== 'omp-rpc') {
      return await startAcpChat({
        harness,
        cwd,
        body: body as Record<string, unknown>,
        model: body.provider && body.modelId ? { provider: String(body.provider), modelId: String(body.modelId) } : null,
        accessMode,
      });
    }
    const { session, realSessionId } = await startNewRpcSession(cwd, accessMode, modeEnv);

    const { type, message, images, provider, modelId, thinkingLevel } = body as {
      type: string;
      message?: string;
      images?: { data: string; mimeType: string }[];
      provider?: string;
      modelId?: string;
      thinkingLevel?: string;
    };

    // The workspace's own default is the FIRST fallback: "Defaults for new
    // chats" exists to decide the model a chat starts on, so a project pick
    // outranks Kabmo's global one for a chat born in that project.
    const projectModel = await projectModelForCwd(await getDb(), cwd);
    const effectiveModel = provider && modelId
      ? { provider, modelId }
      : projectModel ?? await loadPersistedModel();
    if (effectiveModel) {
      await session.send({ type: 'set_model', ...effectiveModel }).catch(() => {});
    }
    if (thinkingLevel) {
      await session.send({ type: 'set_thinking_level', level: thinkingLevel }).catch(() => {});
    }

    if (type === 'ensure_session') {
      // Seeded client-side before the JSONL has a model_change entry. The
      // RESOLVED model is what the child is actually serving with — omp may pick
      // its own default or resolve an alias, and `effectiveModel` is only what we
      // asked for. The generating indicator names this value from the first
      // frame, so a seed built from the request alone can report a model the
      // answer does not come from.
      const resolvedModel = session.runModel ?? effectiveModel;
      return json({ success: true, sessionId: realSessionId, model: resolvedModel, data: null });
    }

    if (type === 'prompt') {
      const ack = await session.send({
        type: 'prompt',
        message: message ?? '',
        ...(images?.length ? { images } : {}),
      });
      // A brand-new chat's first prompt belongs in the recall list too, under
      // the id the child just reported.
      await recordPrompt(realSessionId, message ?? '');
      return json({ success: true, sessionId: realSessionId, data: ack });
    }

    return json({ error: `Unsupported command: ${type}` }, { status: 400 });
  } catch (error) {
    return rpcErrorResponse(error);
  }
}

/**
 * The ACP half of this route: spawn the agent, apply the picks, run the first
 * prompt. Kept in the same file because both branches answer the SAME shapes
 * (`{sessionId, model}` / `{sessionId, data}`), and a client must not be able to
 * tell which transport served a new chat.
 */
async function startAcpChat({ harness, cwd, body, model, accessMode }: {
  harness: HarnessId;
  cwd: string;
  body: Record<string, unknown>;
  model: { provider: string; modelId: string } | null;
  accessMode: ApprovalMode;
}): Promise<Response> {
  const type = String(body.type ?? '');
  const thinkingLevel = typeof body.thinkingLevel === 'string' ? body.thinkingLevel : null;
  const mode = harnessModeSelection(body);
  const { token, env: agentEnv } = mintAgentEnvironment();
  const { session, realSessionId, adopted } = await startAcpSession({
    harness,
    sessionId: `__new__${Bun.randomUUIDv7()}`,
    cwd,
    // The composer's pick, else the HARNESS's own configured default — resolved
    // inside `startAcpSession` against what the agent published. omp's project
    // and global model picks are deliberately NOT consulted: they name models
    // this agent does not serve, and a value it happens to list would silently
    // start the chat on a model the user never chose for it.
    model,
    thinkingLevel,
    mode,
    accessMode,
    env: agentEnv,
    // A pending chat's prewarm (fired when the harness was picked) is this
    // chat's to adopt: the boot already happened while the prompt was written.
    claimPrewarmed: true,
  });
  // A claimed warm child already recorded the token its environment carries;
  // overwriting it here invalidated every callback that agent makes.
  if (!adopted) {
    await rememberAgentToken(realSessionId, token).catch((cause: unknown) => {
      console.error(`[sessions] could not record the agent token for ${realSessionId}:`, cause);
    });
  }

  if (type === 'ensure_session') {
    return json({ success: true, sessionId: realSessionId, model: session.runModel, data: null, harness });
  }
  if (type === 'prompt') {
    const ack = await session.send({
      type: 'prompt',
      message: typeof body.message === 'string' ? body.message : '',
      ...(Array.isArray(body.images) && body.images.length > 0 ? { images: body.images } : {}),
    });
    await recordPrompt(realSessionId, typeof body.message === 'string' ? body.message : '');
    return json({ success: true, sessionId: realSessionId, data: ack, harness });
  }
  return json({ error: `Unsupported command: ${type}` }, { status: 400 });
}

/**
 * The ACP mode id a new chat asked for, when the composer sent one.
 *
 * Exported for its ONE contract: which of the two spellings wins. The route's
 * ACP branch is a spawn, so this mapping is where a composer pick either reaches
 * the agent or is silently dropped.
 */
export function harnessModeSelection(body: Record<string, unknown>): string | null {
  // The composer's own mode ladder (a pending chat's pick from the harness
  // probe). It wins over the Plan flag: the ladder IS the agent's vocabulary,
  // and 'plan' is just one of its values.
  if (typeof body.sessionMode === 'string' && body.sessionMode.trim()) return body.sessionMode;
  const modes = asRecord(body.modes);
  if (modes.plan === true) return 'plan';
  return null;
}
