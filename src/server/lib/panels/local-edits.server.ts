/**
 * Whether a user has edited an installed plugin's files.
 *
 * The bundled sync REPLACES an install's files with the store's copy, so it has
 * to know whether those files are still the ones it put there. Nothing on disk
 * answers that: the install is an ordinary directory, and a store update changes
 * the STORE rather than the install, so comparing the two trees would report
 * every legitimate version bump as a local edit.
 *
 * The reference is therefore a baseline — the hash of every tracked file, taken
 * when the install was written and re-taken after each sync. A file whose hash
 * moved, or a file that appeared or vanished, is an edit; the whole plugin is
 * then left alone rather than merged, because a half-updated plugin is a version
 * that exists nowhere.
 *
 * **`node_modules` and the lockfiles are always excluded, because the install's
 * own build writes them.** Tracking them would mark every plugin as edited the
 * first time it built, and the sync would then never run again.
 *
 * **`dist` is excluded only when the plugin has SOURCE.** That is the whole
 * subtlety: a plugin with `src/` has its bundle generated by the build this
 * chamber runs, so `dist` is output and its hashes would change on every build;
 * a plugin with no source DISTRIBUTES its bundle, and there `dist` is content the
 * user can edit — excluding it would let the sync silently overwrite an edited
 * bundle. `buildPanelPlugin` reports `not-a-package` for the second shape, which
 * is the same distinction this makes.
 */

import { readdir } from 'fs/promises';
import type { Dirent } from 'fs';
import { join, relative, sep } from 'path';
import { pathExists } from '@/server/lib/omp/core/paths';
import { APP_SOURCE_CANDIDATES, SERVER_SOURCE_CANDIDATES, findSource } from '@/server/lib/panels/build-targets.server';

/** Directories a plugin's own tooling writes, and the clone metadata. */
const EXCLUDED_DIRS = new Set(['node_modules', '.git']);

/** Lockfiles `bun install` writes into the plugin root. */
const EXCLUDED_FILES = new Set(['bun.lock', 'bun.lockb']);

/** A file's path (relative, POSIX) to the hash of its bytes. */
export type TrackedFileHashes = Record<string, string>;

/**
 * Whether the build this chamber runs GENERATES `dist` for this plugin.
 *
 * A `build` script or a source entry means yes; neither means the plugin ships
 * its bundle as-is, so its `dist` is user-editable content rather than output.
 */
async function generatesItsOwnBundle(root: string): Promise<boolean> {
  if (await pathExists(join(root, 'package.json'))) {
    try {
      const parsed: unknown = await Bun.file(join(root, 'package.json')).json();
      const scripts = parsed && typeof parsed === 'object' ? (parsed as Record<string, unknown>).scripts : undefined;
      const build = scripts && typeof scripts === 'object' ? (scripts as Record<string, unknown>).build : undefined;
      if (typeof build === 'string' && build.trim()) return true;
    } catch {
      // An unreadable package.json is `buildPanelPlugin`'s error to report.
    }
  }
  const app = await findSource(root, APP_SOURCE_CANDIDATES);
  if (app) return true;
  return (await findSource(root, SERVER_SOURCE_CANDIDATES)) !== null;
}

async function walk(root: string, dir: string, excluded: ReadonlySet<string>, out: TrackedFileHashes): Promise<void> {
  let entries: Dirent[];
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    // An unreadable directory contributes nothing rather than failing the walk:
    // the caller compares maps, and a vanished file already reads as a change.
    return;
  }

  for (const entry of entries) {
    const absolute = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (excluded.has(entry.name)) continue;
      await walk(root, absolute, excluded, out);
      continue;
    }
    // Symlinks and special files are skipped: `entry.isFile()` is false for a
    // symlink, and following one could hash something outside the plugin.
    if (!entry.isFile() || EXCLUDED_FILES.has(entry.name)) continue;
    const key = relative(root, absolute).split(sep).join('/');
    out[key] = Bun.hash(await Bun.file(absolute).arrayBuffer()).toString(36);
  }
}

/**
 * The hash of every tracked file under `dir`. Empty when the directory is gone.
 *
 * The exclusion set is decided once, from the plugin's own shape, so the baseline
 * taken at install time and the one re-taken after a sync describe the same
 * surface — a set that differed between the two would read as an edit that never
 * happened.
 */
export async function hashTrackedFiles(dir: string): Promise<TrackedFileHashes> {
  const out: TrackedFileHashes = {};
  if (!(await pathExists(dir))) return out;
  const excluded = new Set(EXCLUDED_DIRS);
  if (await generatesItsOwnBundle(dir)) excluded.add('dist');
  await walk(dir, dir, excluded, out);
  return out;
}

/**
 * The paths that differ between a baseline and the current tree — added, removed
 * or changed. An empty list means the install is exactly what was written.
 */
export function changedPaths(baseline: TrackedFileHashes, current: TrackedFileHashes): string[] {
  const changed = new Set<string>();
  for (const [path, hash] of Object.entries(baseline)) {
    if (current[path] !== hash) changed.add(path);
  }
  for (const path of Object.keys(current)) {
    if (!(path in baseline)) changed.add(path);
  }
  return [...changed].sort();
}
